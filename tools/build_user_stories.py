#!/usr/bin/env python3
"""Generate the MVP user stories document from the graph.

Writes docs/user-stories/: one file per persona, where each MVP screen is a story whose acceptance
criteria are its rules, plus the business rules those screens save through, the platform behavior
behind them, and the open questions they rest on. The files are a view of the graph, so they are
never edited by hand. --check writes nothing and fails when a file is missing, stale, or extra, as
CI runs it.
"""

from __future__ import annotations

import argparse
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from irisgraph import REPO_ROOT, REQUIREMENT_ID_IN_TEXT, Graph, load_graph  # noqa: E402
from list_decisions import OWNERS  # noqa: E402

OUTPUT_DIR = Path("docs") / "user-stories"
PHASE = "MVP"
HEADER = (
    "<!-- Generated by tools/build_user_stories.py from the requirements graph. "
    "Do not edit; change the graph and run the script. -->"
)

ROLE_LABELS = {
    "INSTAWORK_ADMIN": "Instawork Admin",
    "PROGRAM_USER": "Program User",
    "UNIT_USER": "Unit User",
    "AGENCY_USER": "Agency User",
    "WORKER": "Worker",
    "SYSTEM": "Iris",
}

PERSONA_FILES = [
    ("unit-user.md", "Unit User stories", ["UNIT-WEB"], "UNIT_USER"),
    ("agency-user.md", "Agency User stories", ["AGENCY-WEB"], "AGENCY_USER"),
    ("program-user.md", "Program User stories", ["PROGRAM-WEB"], "PROGRAM_USER"),
    ("instawork-admin.md", "Instawork Admin stories", ["ADMIN-WEB"], "INSTAWORK_ADMIN"),
    ("every-user.md", "Stories every user shares", ["SHELL", "ASSISTANT"], None),
]
BUSINESS_RULES_FILE = "business-rules.md"
PLATFORM_FILE = "behind-the-scenes.md"
QUESTIONS_FILE = "open-questions.md"

SOURCE_LABELS = {
    "SHEET": "Compass sheet",
    "START": "Confluence pantry",
    "FEEDBACK": "Demo feedback",
    "SESSIONS": "Demo sessions",
    "SLACK": "Working group",
    "PRD": "PRD",
    "OPS": "Product Ops",
    "FAQ": "FAQ",
    "DEMO": "Demo app",
    "GRAPH": "Graph",
}

REFERENCE = re.compile(rf"{REQUIREMENT_ID_IN_TEXT.pattern}(?:\.R\d+)?")


def anchor(identifier: str) -> str:
    return identifier.lower()


def mvp(graph: Graph, layer: str | None = None, modules: list[str] | None = None) -> list[dict]:
    docs = [
        doc
        for doc in graph.requirements.values()
        if doc.get("requirement_phase") == PHASE
        and (layer is None or doc.get("requirement_target_layer") == layer)
        and (modules is None or doc.get("requirement_target_module") in modules)
    ]
    return sorted(docs, key=lambda doc: doc["requirement_id"])


def file_for(graph: Graph) -> dict[str, str]:
    """Where each MVP requirement is written, so links resolve across files."""
    placement = {}
    for name, _title, modules, _role in PERSONA_FILES:
        for doc in mvp(graph, "user-interface", modules):
            placement[doc["requirement_id"]] = name
    for doc in mvp(graph, "product"):
        placement[doc["requirement_id"]] = BUSINESS_RULES_FILE
    for doc in mvp(graph, "platform"):
        placement[doc["requirement_id"]] = PLATFORM_FILE
    return placement


def decisions_of(doc: dict) -> list[str]:
    cited = list(doc.get("requirement_decisions") or [])
    for rule in doc.get("requirement_rules") or []:
        cited.extend(rule.get("rule_decisions") or [])
    seen = dict.fromkeys(cited)
    return sorted(seen, key=lambda decision_id: int(decision_id.split("-")[1]))


class Writer:
    def __init__(self, graph: Graph):
        self.graph = graph
        self.placement = file_for(graph)
        self.first_slice = graph.starting_flow()
        self.screens_using: dict[str, list[str]] = defaultdict(list)
        for requirement_id, name in self.placement.items():
            if name in {persona[0] for persona in PERSONA_FILES}:
                for dependency in graph.depends_on(requirement_id):
                    self.screens_using[dependency].append(requirement_id)
        self.citing: dict[str, list[str]] = defaultdict(list)
        for requirement_id in sorted(self.placement):
            for decision_id in decisions_of(graph.requirements[requirement_id]):
                self.citing[decision_id].append(requirement_id)

    def link(self, requirement_id: str, from_file: str, with_title: bool = False) -> str:
        name = self.placement.get(requirement_id)
        if name is None:
            return f"`{requirement_id}`"
        target = f"#{anchor(requirement_id)}" if name == from_file else f"{name}#{anchor(requirement_id)}"
        label = f"`{requirement_id}`"
        if with_title:
            label += f" {self.graph.requirements[requirement_id]['requirement_title']}"
        return f"[{label}]({target})"

    def text(self, value: str, from_file: str) -> str:
        """Requirement text with each requirement it names linked, keeping any rule suffix."""

        def replace(match: re.Match) -> str:
            whole = match.group(0)
            requirement_id = whole.split(".")[0]
            name = self.placement.get(requirement_id)
            if name is None:
                return f"`{whole}`"
            target = f"#{anchor(requirement_id)}" if name == from_file else f"{name}#{anchor(requirement_id)}"
            return f"[`{whole}`]({target})"

        return REFERENCE.sub(replace, " ".join(str(value).split()))

    def who(self, doc: dict) -> str:
        return ", ".join(ROLE_LABELS.get(actor, actor) for actor in doc.get("requirement_actors") or [])

    def features(self, doc: dict) -> list[str]:
        """The sheet features a requirement delivers: those it lists, then any sheet line it cites."""
        found = list(doc.get("requirement_features") or [])
        for source in doc.get("requirement_sources") or []:
            key, _, detail = str(source).partition(" ")
            if key == "SHEET" and detail in self.graph.features:
                found.append(detail)
        return list(dict.fromkeys(found))

    def why(self, doc: dict) -> list[str]:
        lines = []
        for feature_id in self.features(doc):
            feature = self.graph.features.get(feature_id) or {}
            reason = " ".join(str(feature.get("why") or "").split())
            what = " ".join(str(feature.get("feature") or "").split())
            lines.append(f"{reason} *({feature_id}: {what})*")
        return lines

    def sources(self, doc: dict) -> str:
        parts = []
        for source in doc.get("requirement_sources") or []:
            key, _, detail = str(source).partition(" ")
            entry = self.graph.sources.get(key) or {}
            label = SOURCE_LABELS.get(key, key)
            url = " ".join(str(entry.get("url") or "").split())
            name = f"[{label}]({url})" if url else label
            parts.append(f"{name} {detail}".strip())
        return "; ".join(parts)

    def questions(self, doc: dict, from_file: str) -> list[str]:
        links = []
        for decision_id in decisions_of(doc):
            decision = self.graph.decisions.get(decision_id) or {}
            question = " ".join(str(decision.get("question") or "").split())
            target = f"#{anchor(decision_id)}" if from_file == QUESTIONS_FILE else f"{QUESTIONS_FILE}#{anchor(decision_id)}"
            links.append(f"[{decision_id}]({target}) {question}")
        return links

    def requirement(self, doc: dict, from_file: str, criteria_label: str, show_builds_on: bool) -> list[str]:
        requirement_id = doc["requirement_id"]
        lines = [f'<a id="{anchor(requirement_id)}"></a>', "", f"### {doc['requirement_title']}", ""]
        tags = [f"`{requirement_id}`"]
        if requirement_id in self.first_slice:
            tags.append("first slice")
        lines += [" · ".join(tags), ""]
        lines.append(f"- **Who:** {self.who(doc)}")
        lines.append(f"- **What:** {self.text(doc['requirement_statement'], from_file)}")
        reasons = self.why(doc)
        if len(reasons) == 1:
            lines.append(f"- **Why:** {reasons[0]}")
        elif reasons:
            lines.append("- **Why:**")
            lines += [f"  - {reason}" for reason in reasons]
        else:
            lines.append("- **Why:** Not given in Compass's sheet; the sources below are where it comes from.")
        if doc.get("requirement_sources"):
            lines.append(f"- **Sources:** {self.sources(doc)}")
        lines += ["", f"**{criteria_label}**", ""]
        for rule in doc.get("requirement_rules") or []:
            lines.append(f"- **{rule['rule_id']}.** {self.text(rule['rule_statement'], from_file)}")
        if show_builds_on:
            builds_on = [
                dependency
                for dependency in self.graph.depends_on(requirement_id)
                if self.placement.get(dependency) == BUSINESS_RULES_FILE
            ]
            if builds_on:
                lines += ["", "**Business rules it saves through**", ""]
                lines += [f"- {self.link(dependency, from_file, with_title=True)}" for dependency in builds_on]
        else:
            screens = self.screens_using.get(requirement_id) or []
            if screens:
                lines += ["", "**Screens that use it**", ""]
                lines += [f"- {self.link(screen, from_file, with_title=True)}" for screen in screens]
        questions = self.questions(doc, from_file)
        if questions:
            lines += ["", "**Open questions it rests on**", ""]
            lines += [f"- {question}" for question in questions]
        lines.append("")
        return lines

    def persona(self, name: str, title: str, modules: list[str], role: str | None) -> str:
        lines = [HEADER, "", f"# {title}", ""]
        if role:
            meaning = next(
                (value["meaning"] for value in self.graph.enums["Role"]["values"] if value["value"] == role),
                "",
            )
            lines += [f"**{ROLE_LABELS[role]}:** {self.text(meaning, name)}", ""]
        else:
            lines += ["The sign-in, page frame, inbox, uploads, and assistant that every persona uses.", ""]
        for module_id in modules:
            module = self.graph.modules[module_id]
            docs = mvp(self.graph, "user-interface", [module_id])
            if len(modules) > 1:
                lines += [f"## {module['module_name']}", "", " ".join(str(module.get("about") or "").split()), ""]
            for doc in docs:
                lines += self.requirement(doc, name, "Acceptance criteria", show_builds_on=True)
        return "\n".join(lines).rstrip() + "\n"

    def layer_file(self, name: str, title: str, intro: str, layer: str) -> str:
        lines = [HEADER, "", f"# {title}", "", intro, ""]
        modules = [module for module in self.graph.modules.values() if module.get("layer") == layer]
        for module in modules:
            docs = mvp(self.graph, layer, [module["module_id"]])
            if not docs:
                continue
            lines += [f"## {module['module_name']}", "", " ".join(str(module.get("about") or "").split()), ""]
            for doc in docs:
                lines += self.requirement(doc, name, "Rules", show_builds_on=False)
        return "\n".join(lines).rstrip() + "\n"

    def open_questions(self) -> str:
        cited = {decision_id for decision_id in self.citing if decision_id in self.graph.decisions}
        counts: Counter = Counter({decision_id: len(self.citing[decision_id]) for decision_id in cited})
        lines = [
            HEADER,
            "",
            "# Open questions",
            "",
            f"The {len(cited)} decisions the MVP stories rest on, grouped by who must answer them and most-cited "
            "first. Each story is written to the assumption until the decision is answered.",
            "",
        ]
        for owner, label in OWNERS.items():
            owned = [self.graph.decisions[decision_id] for decision_id in cited if self.graph.decisions[decision_id].get("answer_from") == owner]
            if not owned:
                continue
            owned.sort(key=lambda d: (not d.get("blocking"), -counts[d["decision_id"]], int(d["decision_id"].split("-")[1])))
            lines += [f"## {label} ({len(owned)})", ""]
            for decision in owned:
                decision_id = decision["decision_id"]
                status = "answered" if decision.get("status") == "answered" else "open"
                if decision.get("blocking"):
                    status += ", blocking"
                lines += [
                    f'<a id="{anchor(decision_id)}"></a>',
                    "",
                    f"### {decision_id}: {' '.join(str(decision['question']).split())}",
                    "",
                    f"- **Status:** {status}",
                ]
                if decision.get("answer"):
                    lines.append(f"- **Answer:** {' '.join(str(decision['answer']).split())}")
                else:
                    lines.append(f"- **Assumed until answered:** {self.text(decision.get('assumption') or '', QUESTIONS_FILE)}")
                users = ", ".join(self.link(requirement_id, QUESTIONS_FILE) for requirement_id in self.citing[decision_id])
                lines += [f"- **Cited by:** {users}", ""]
        return "\n".join(lines).rstrip() + "\n"

    def index(self) -> str:
        stories = mvp(self.graph, "user-interface")
        rules = sum(len(doc.get("requirement_rules") or []) for doc in stories)
        reviewed = sum(1 for doc in mvp(self.graph) if (doc.get("requirement_review") or {}).get("status") == "approved")
        no_reason = sum(1 for doc in stories if not self.features(doc))
        cited = [decision_id for decision_id in self.citing if decision_id in self.graph.decisions]
        open_cited = sum(1 for decision_id in cited if self.graph.decisions[decision_id].get("status") != "answered")
        lines = [
            HEADER,
            "",
            "# Iris user stories: MVP",
            "",
            "Iris is Instawork's vendor management system for Compass. These are its "
            f"{len(stories)} MVP screens, one story each, with {rules} acceptance criteria, grouped by the persona "
            "who uses them.",
            "",
            "## Status",
            "",
            f"- **Review:** {reviewed} of {len(mvp(self.graph))} MVP requirements are approved. Every story is a "
            "draft until its requirement is reviewed.",
            f"- **Open questions:** {open_cited} of the {len(cited)} decisions these stories rest on are unanswered. "
            f"Each story is written to the assumption; see [{QUESTIONS_FILE}]({QUESTIONS_FILE}).",
            f"- **Reasons:** {len(stories) - no_reason} stories carry Compass's own reason from its sheet. The other "
            f"{no_reason} say so, and name the document they come from.",
            "",
            "## How to read a story",
            "",
            "- **Who** is the persona the screen is for.",
            "- **What** is the requirement's statement.",
            "- **Why** is Compass's reason, from the sheet feature the screen delivers.",
            "- **Acceptance criteria** are the screen's rules, numbered as in the graph, so a test or a review "
            "can cite one as `REQ-UNIT-WEB-0002.R3`.",
            "- **Business rules it saves through** are the product requirements behind the screen. Their rules "
            "hold for every way in, whether a screen, a file, or the assistant.",
            "- **Open questions it rests on** are the decisions the story assumes.",
            "- **First slice** marks a story in the first end-to-end slice the team builds.",
            "",
            "## Stories",
            "",
        ]
        for name, title, modules, _role in PERSONA_FILES:
            docs = mvp(self.graph, "user-interface", modules)
            lines += [f"### [{title}]({name}) ({len(docs)})", ""]
            lines += [f"- {self.link(doc['requirement_id'], 'README.md', with_title=True)}" for doc in docs]
            lines.append("")
        lines += [
            "## Reference",
            "",
            f"- [Business rules]({BUSINESS_RULES_FILE}): the {len(mvp(self.graph, 'product'))} MVP product "
            "requirements the screens save through.",
            f"- [Behind the scenes]({PLATFORM_FILE}): the {len(mvp(self.graph, 'platform'))} MVP platform "
            "requirements, such as sign-in, file reading, messages, the audit trail, and scheduled jobs.",
            f"- [Open questions]({QUESTIONS_FILE}): every decision the stories rest on, by who must answer it.",
            "",
        ]
        return "\n".join(lines).rstrip() + "\n"


def render(graph: Graph) -> dict[str, str]:
    writer = Writer(graph)
    files = {"README.md": writer.index()}
    for name, title, modules, role in PERSONA_FILES:
        files[name] = writer.persona(name, title, modules, role)
    files[BUSINESS_RULES_FILE] = writer.layer_file(
        BUSINESS_RULES_FILE,
        "Business rules",
        "The MVP product requirements the screens save through. Their rules hold however a change arrives: "
        "a screen, a file, an email, or the assistant.",
        "product",
    )
    files[PLATFORM_FILE] = writer.layer_file(
        PLATFORM_FILE,
        "Behind the scenes",
        "The MVP platform requirements every story relies on and no screen shows directly.",
        "platform",
    )
    files[QUESTIONS_FILE] = writer.open_questions()
    return files


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", default=str(REPO_ROOT))
    parser.add_argument("--check", action="store_true", help="write nothing; fail if docs/user-stories is out of date")
    args = parser.parse_args(argv)
    root = Path(args.root)
    output = root / OUTPUT_DIR
    files = render(load_graph(root))
    existing = {path.name for path in output.glob("*.md")} if output.exists() else set()
    if args.check:
        stale = sorted(name for name, text in files.items() if not (output / name).exists() or (output / name).read_text() != text)
        extra = sorted(existing - set(files))
        for name in stale:
            print(f"{OUTPUT_DIR / name} is out of date")
        for name in extra:
            print(f"{OUTPUT_DIR / name} is not generated by this script")
        if stale or extra:
            print("run: python tools/build_user_stories.py")
            return 1
        print(f"{OUTPUT_DIR} is up to date ({len(files)} files)")
        return 0
    output.mkdir(parents=True, exist_ok=True)
    for name in existing - set(files):
        (output / name).unlink()
    for name, text in files.items():
        (output / name).write_text(text)
    print(f"wrote {OUTPUT_DIR} ({len(files)} files, {sum(len(text) for text in files.values()) // 1024} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
